"""
Booking factory for test fixtures.

Since PR #(this) a booking is a cart (one row in ``bookings``, N rows in
``booking_items``). The factory keeps a ``service_id`` keyword for backward
compat — legacy tests pass it and expect a one-item cart — and now also
accepts ``item_service_ids`` for multi-item scenarios. Passing both is an
error at the call site rather than a silent precedence rule.

Every item's ``service`` relationship is populated on the returned booking
via ``set_committed_value``. Serialisation paths declare that relationship
``raise_on_sql`` (mirrors ``consumer_address``), so a test that constructs
a booking and hands it straight to ``BookingResponse.for_viewer`` would
otherwise fault the moment pydantic reads ``item.service.name``. When the
caller passes a real ``service_id`` we load the row; when they let the
factory generate one, we create a matching Service row so the relationship
resolves to a real object either way.
"""

import uuid
from collections.abc import Sequence

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm.attributes import set_committed_value

from app.models.booking import Booking, BookingStatus, PaymentMethod, PaymentStatus
from app.models.booking_item import BookingItem
from app.models.category import Category
from app.models.service import Service


class BookingFactory:
    @staticmethod
    async def create(
        db: AsyncSession,
        consumer_id: uuid.UUID,
        provider_id: uuid.UUID,
        service_id: uuid.UUID | None = None,
        item_service_ids: Sequence[uuid.UUID] | None = None,
        address_id: uuid.UUID | None = None,
        status: BookingStatus = BookingStatus.REQUESTED,
        payment_status: PaymentStatus = PaymentStatus.PENDING,
        service_amount: float = 100.0,
        platform_commission: float = 20.0,
        provider_payout: float = 80.0,
        doorstep_otp: str = "1234",
        payment_method: PaymentMethod = PaymentMethod.ONLINE,
        razorpay_order_id: str | None = None,
    ) -> Booking:
        if service_id is not None and item_service_ids is not None:
            raise ValueError("Pass either service_id or item_service_ids, not both")

        # Legacy single-service call: build a 1-item cart with the same id
        # the caller supplied (or a fresh one). Multi-service call: create
        # one item per id. The per-item amounts split the booking totals
        # evenly — good enough for tests that assert on `booking.provider_payout`
        # (the sum), which is by far the common expectation.
        resolved_ids: list[uuid.UUID] = (
            list(item_service_ids) if item_service_ids is not None else [service_id or uuid.uuid4()]
        )
        n = len(resolved_ids)
        per_item_amount = round(service_amount / n, 2)
        per_item_commission = round(platform_commission / n, 2)
        per_item_payout = round(provider_payout / n, 2)

        booking = Booking(
            id=uuid.uuid4(),
            consumer_id=consumer_id,
            provider_id=provider_id,
            consumer_address_id=address_id or uuid.uuid4(),
            status=status,
            payment_status=payment_status,
            doorstep_otp=doorstep_otp,
            service_amount=service_amount,
            platform_commission=platform_commission,
            provider_payout=provider_payout,
            payment_method=payment_method,
            razorpay_order_id=razorpay_order_id,
        )
        db.add(booking)
        await db.flush()

        # Materialise every service the items point at — if a row already
        # exists (real ``service_id`` passed) we reuse it; if not (fresh id
        # generated by this factory) we create one. Either way,
        # ``item.service`` is a real, loaded Service by the time we return,
        # so ``BookingItemResponse.from_item`` never trips
        # ``BookingItem.service``'s raise_on_sql loader.
        existing = (
            (await db.execute(select(Service).where(Service.id.in_(resolved_ids)))).scalars().all()
        )
        existing_by_id = {s.id: s for s in existing}
        placeholder_cat: Category | None = None
        for svc_id in resolved_ids:
            if svc_id in existing_by_id:
                continue
            # Need a category to hang the placeholder service off — one
            # shared row for the whole factory call, reused if the cart
            # has multiple synthetic services.
            if placeholder_cat is None:
                placeholder_cat = Category(
                    name=f"Factory Cat {uuid.uuid4()}",
                    slug=f"factory-cat-{uuid.uuid4()}",
                    is_active=True,
                    sort_order=0,
                )
                db.add(placeholder_cat)
                await db.flush()
            fake_service = Service(
                id=svc_id,
                category_id=placeholder_cat.id,
                name=f"Factory Service {svc_id}",
                base_price=per_item_amount,
                duration_minutes=60,
                is_active=True,
            )
            db.add(fake_service)
            existing_by_id[svc_id] = fake_service
        await db.flush()

        items: list[BookingItem] = []
        for svc_id in resolved_ids:
            item = BookingItem(
                booking_id=booking.id,
                service_id=svc_id,
                quantity=1,
                unit_price=per_item_amount,
                total_price=per_item_amount,
                platform_commission=per_item_commission,
                provider_payout=per_item_payout,
            )
            db.add(item)
            # Preload the service relationship on this item so
            # BookingItemResponse.from_item (and any caller reading
            # item.service.name) doesn't fault on raise_on_sql.
            set_committed_value(item, "service", existing_by_id[svc_id])
            items.append(item)
        await db.flush()
        # Hand the items to the relationship as *loaded* so callers can
        # read booking.items without tripping the raise_on_sql sentinel —
        # mirrors how BookingService.create_booking hydrates.
        set_committed_value(booking, "items", items)

        return booking
